import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';
const components = [
  ['src/routes/+page.svelte', '.launcher'],
  ['src/lib/components/PrimaryNav.svelte', '.primary-nav'],
  ['src/routes/spaces/[spaceId]/[...view]/+page.svelte', '.ui-space'],
  ['src/routes/settings/+page.svelte', '.settings-page'],
  ['src/routes/login/+page.svelte', '.login-page'],
  ['src/routes/setup/+page.svelte', '.setup-page'],
  ['src/lib/components/AppSettings.svelte', '.app-settings'],
  ['src/lib/components/AutomationSettings.svelte', '.automation-card'],
  ['src/lib/components/ConnectChatGPT.svelte', '.connect-chatgpt'],
  ['src/lib/components/ChatView.svelte', '.ui-chat'],
  ['src/lib/components/BuildPlanCard.svelte', '.build-plan'],
  ['src/lib/components/VoiceActions.svelte', '.ui-voice-actions'],
];
let output =
  '/* Preserved component styles from the Svelte frontend. Generated by preserve-styles.mjs. */\n';
for (const [file, scope] of components) {
  const source = readFileSync(file, 'utf8').match(/<style>([\s\S]*?)<\/style>/)?.[1];
  if (!source) continue;
  const root = postcss.parse(source);
  root.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && rule.parent.name.includes('keyframes')) return;
    rule.selectors = rule.selectors.map((selector) => {
      if (scope === '.launcher' && selector.startsWith('.has-apps'))
        selector = '.launcher' + selector;
      selector = selector.replace(/:global\(([^)]+)\)/g, '$1');
      return selector.startsWith(scope) ? selector : `:where(${scope}) ${selector}`;
    });
  });
  output += `\n/* ${file} */\n${root.toString()}\n`;
}
writeFileSync('web/preserved.css', output);
