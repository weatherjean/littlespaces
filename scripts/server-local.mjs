import {mkdirSync,writeFileSync,cpSync} from 'node:fs';
import {join} from 'node:path';
import {homedir} from 'node:os';
import {execFileSync} from 'node:child_process';
const root=process.cwd(),units=join(homedir(),'.config/systemd/user');
const release=join(root,'.data/runtime/app-servers',String(Date.now()));
mkdirSync(join(release,'scripts'),{recursive:true});
cpSync(join(root,'scripts/server.ts'),join(release,'scripts/server.ts'));
cpSync(join(root,'src/lib'),join(release,'src/lib'),{recursive:true});
mkdirSync(units,{recursive:true});
writeFileSync(join(units,'little-spaces-app-server.service'),`[Unit]\nDescription=Little Spaces app storage and execution server\nAfter=network.target\n\n[Service]\nType=simple\nWorkingDirectory=${root}\nExecStart=${process.execPath} ${root}/node_modules/tsx/dist/cli.mjs ${release}/scripts/server.ts\nEnvironment=APP_SERVER_HOST=127.0.0.1\nEnvironment=APP_SERVER_PORT=5175\nRestart=on-failure\nRestartSec=2\n\n[Install]\nWantedBy=default.target\n`);
execFileSync('systemctl',['--user','daemon-reload']);
execFileSync('systemctl',['--user','enable','little-spaces-app-server.service'],{stdio:'inherit'});
execFileSync('systemctl',['--user','restart','little-spaces-app-server.service'],{stdio:'inherit'});
console.log('App server managed by little-spaces-app-server.service on 127.0.0.1:5175.');
