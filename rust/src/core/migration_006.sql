CREATE TABLE owner_profile(id INTEGER PRIMARY KEY CHECK(id=1), email TEXT NOT NULL UNIQUE);
CREATE TABLE guests(id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL);
CREATE TABLE guest_apps(guest TEXT NOT NULL REFERENCES guests(id) ON DELETE CASCADE, app TEXT NOT NULL REFERENCES apps(id) ON DELETE CASCADE, PRIMARY KEY(guest,app));
CREATE TABLE guest_sessions(id TEXT PRIMARY KEY, guest TEXT NOT NULL REFERENCES guests(id) ON DELETE CASCADE, expires_at INTEGER NOT NULL, csrf TEXT NOT NULL);
PRAGMA user_version=6;
