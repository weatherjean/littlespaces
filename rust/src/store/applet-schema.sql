CREATE TABLE IF NOT EXISTS records(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS revisions(
    version INTEGER PRIMARY KEY AUTOINCREMENT,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    source TEXT NOT NULL,
    bundle TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE TABLE IF NOT EXISTS photos(id TEXT PRIMARY KEY,owner TEXT NOT NULL,name TEXT NOT NULL,mime TEXT NOT NULL,width INTEGER NOT NULL,height INTEGER NOT NULL,bytes INTEGER NOT NULL,data BLOB NOT NULL,created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')));
CREATE TABLE IF NOT EXISTS backend_contracts(hash TEXT PRIMARY KEY,contract TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS http_grants(id INTEGER PRIMARY KEY CHECK(id=1),grants TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS external_operations(id TEXT PRIMARY KEY,action TEXT NOT NULL,origin TEXT NOT NULL,method TEXT NOT NULL,status TEXT NOT NULL,http_status INTEGER,created_at TEXT NOT NULL,updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS app_diagnostics(id INTEGER PRIMARY KEY AUTOINCREMENT,version INTEGER NOT NULL,kind TEXT NOT NULL,data TEXT NOT NULL,created_at TEXT NOT NULL);
